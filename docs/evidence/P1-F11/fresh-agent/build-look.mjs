// build-look.mjs: assembles look.js from the verbatim `look.js#...` blocks in recipes.md (TSL route).
// The skill gives the blocks but no import header; the header below is my own (guessed from the identifiers used).
import fs from 'node:fs';
const md = fs.readFileSync(new URL('../../../../.claude/skills/jammers-look/recipes.md', import.meta.url), 'utf8');
const re = /<!-- recipe: (look\.js#[\w-]+) -->\n```js\n([\s\S]*?)\n```\n<!-- \/recipe -->/g;
const blocks = new Map();
for (const m of md.matchAll(re)) blocks.set(m[1], m[2]);
const order = ['tokens', 'tiers', 'look-uniforms', 'rig', 'toon-model', 'car-attributes', 'paint-key', 'damage', 'grit', 'material', 'speed-lines', 'post'];
const header = `// GENERATED by build-look.mjs from .claude/skills/jammers-look/recipes.md (look.js#* blocks, verbatim). Do not edit.
import * as THREE from 'three/webgpu';
import {
  uniform, property, float, vec2, vec3, vec4, normalView, fwidth, mix, smoothstep, BRDF_Lambert, diffuseColor, attribute,
  step, min, max, positionGeometry, positionWorld, normalWorld, mx_noise_float, hash, fract, floor, luminance, length, mrt,
  atan, time, abs, screenUV, Fn, pass, output, emissive, directionToColor, colorToDirection, perspectiveDepthToViewZ,
  screenSize, dot, saturate, mat2, cos, sin, screenCoordinate, renderOutput,
} from 'three/tsl';
import { bloom } from 'three/addons/tsl/display/BloomNode.js';
import { fxaa } from 'three/addons/tsl/display/FXAANode.js';
`;
let out = header;
for (const k of order) {
  const b = blocks.get('look.js#' + k);
  if (!b) throw new Error('missing block ' + k);
  out += `\n// region: ${k}\n${b}\n`;
}
fs.writeFileSync(new URL('./look.js', import.meta.url), out);
console.log('wrote look.js,', out.length, 'bytes,', order.length, 'blocks');
